// Helper function to check if API call failed
export const useDemoData = (apiData: any, demoData: any) => {
  if (apiData && apiData.data && apiData.data.length > 0) {
    return apiData
  }
  if (apiData && Array.isArray(apiData) && apiData.length > 0) {
    return { data: apiData, success: true }
  }
  return { data: demoData, success: true, isDemo: true }
}

